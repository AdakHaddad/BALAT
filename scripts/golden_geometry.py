#!/usr/bin/env python3
"""Golden geometry model and demo-trace generator for the Basys 3 demo.

The integer functions below mirror rtl/road_geom.v exactly, including the
Q14 direction and arithmetic shift. Run this script to regenerate:

    data/demo_trace.csv
    data/demo_trace_expected.csv
    rtl/demo_trace_rom.v
    tb/road_geom_vectors.txt

No third-party packages are required.
"""

from __future__ import annotations

import csv
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

Q_SHIFT = 14
Q_ONE = 1 << Q_SHIFT

ROAD_AX, ROAD_AY = -2000, 0
ROAD_BX, ROAD_BY = 2000, 0
ROAD_UX, ROAD_UY = Q_ONE, 0

TRACE_X = -1500
TRACE_Y_START = 1000
TRACE_Y_STEP = -10
TRACE_SAMPLES = 201  # 1000 cm down to -1000 cm inclusive

CAUTION_CM = 500
DANGER_CM = 200


def rtl_point_seg_dist2(
    px: int,
    py: int,
    ax: int,
    ay: int,
    bx: int,
    by: int,
    ux_q14: int,
    uy_q14: int,
) -> tuple[int, int]:
    """Return (dist2_cm2, inside_span) using the RTL integer algorithm."""
    relx = px - ax
    rely = py - ay
    bax = bx - ax
    bay = by - ay

    along = relx * ux_q14 + rely * uy_q14
    b_along = bax * ux_q14 + bay * uy_q14
    perp = relx * uy_q14 - rely * ux_q14

    if along <= 0:
        dx, dy = relx, rely
        inside = 0
    elif along >= b_along:
        dx, dy = px - bx, py - by
        inside = 0
    else:
        d = perp >> Q_SHIFT
        dx, dy = d, 0
        inside = 1

    return dx * dx + dy * dy, inside


def build_trace() -> list[tuple[int, int]]:
    return [(TRACE_X, TRACE_Y_START + i * TRACE_Y_STEP) for i in range(TRACE_SAMPLES)]


def zone_for(dist2: int) -> str:
    if dist2 <= DANGER_CM * DANGER_CM:
        return "DANGER"
    if dist2 <= CAUTION_CM * CAUTION_CM:
        return "CAUTION"
    return "SAFE"


def write_trace_files(trace: list[tuple[int, int]]) -> None:
    data_dir = REPO / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    with (data_dir / "demo_trace.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["index", "x_cm", "y_cm"])
        for i, (x, y) in enumerate(trace):
            w.writerow([i, x, y])

    with (data_dir / "demo_trace_expected.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["index", "x_cm", "y_cm", "dist2_cm2", "inside_span", "zone"])
        for i, (x, y) in enumerate(trace):
            d2, inside = rtl_point_seg_dist2(
                x, y, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY
            )
            w.writerow([i, x, y, d2, inside, zone_for(d2)])


def write_trace_rom(trace: list[tuple[int, int]]) -> None:
    lines = [
        "// Generated by scripts/golden_geometry.py. Do not edit.",
        "// Packed trace word: {x_cm[15:0], y_cm[15:0]}.",
        "module demo_trace_rom (",
        "    input  wire [15:0] addr,",
        "    output reg  signed [31:0] data",
        ");",
        "",
        "    always @* begin",
        "        case (addr)",
    ]
    for i, (x, y) in enumerate(trace):
        packed = ((x & 0xFFFF) << 16) | (y & 0xFFFF)
        lines.append(f"            16'd{i}: data = 32'h{packed:08X};")
    lines += [
        "            default: data = 32'sd0;",
        "        endcase",
        "    end",
        "",
        "endmodule",
        "",
    ]
    (REPO / "rtl" / "demo_trace_rom.v").write_text("\n".join(lines))


def write_geometry_vectors() -> None:
    cases = [
        # Demo road: horizontal, A=(-2000,0), B=(2000,0), u=(1,0).
        (0, 500, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY),
        (0, 0, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY),
        (0, -200, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY),
        (-3000, 0, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY),
        (3000, 0, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY),
        (-2000, 300, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY),
        (2000, 300, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY),
        (-1500, 1000, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY),
        # Documented coordinate-range corners.
        (1000000, 1000000, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY),
        (-1000000, -1000000, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY),
        # Diagonal road.
        (0, 1000, 0, 0, 1000, 1000, 11585, 11585),
        (500, 0, 0, 0, 1000, 1000, 11585, 11585),
        (-100, 500, 0, 0, 1000, 1000, 11585, 11585),
        (1500, 1500, 0, 0, 1000, 1000, 11585, 11585),
        # Vertical road.
        (300, 0, 0, -1000, 0, 1000, 0, Q_ONE),
        (0, 2000, 0, -1000, 0, 1000, 0, Q_ONE),
        (0, -2000, 0, -1000, 0, 1000, 0, Q_ONE),
        # Zero-length segment.
        (200, 200, 100, 100, 100, 100, 0, 0),
    ]

    lines = []
    for px, py, ax, ay, bx, by, ux, uy in cases:
        d2, inside = rtl_point_seg_dist2(px, py, ax, ay, bx, by, ux, uy)
        lines.append(
            f"{px} {py} {ax} {ay} {bx} {by} {ux} {uy} 0x{d2:016X} {inside}"
        )
    (REPO / "tb" / "road_geom_vectors.txt").write_text("\n".join(lines) + "\n")


def main() -> None:
    trace = build_trace()
    write_trace_files(trace)
    write_trace_rom(trace)
    write_geometry_vectors()

    zones = {"SAFE": 0, "CAUTION": 0, "DANGER": 0}
    for x, y in trace:
        d2, _ = rtl_point_seg_dist2(
            x, y, ROAD_AX, ROAD_AY, ROAD_BX, ROAD_BY, ROAD_UX, ROAD_UY
        )
        zones[zone_for(d2)] += 1

    print(f"Wrote {len(trace)} trace samples")
    print(f"Zone counts: {zones}")
    print("Generated rtl/demo_trace_rom.v and tb/road_geom_vectors.txt")


if __name__ == "__main__":
    main()
